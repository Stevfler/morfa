// Extracts only the icons in src/lib/icons/map.ts from the @iconify-json sets into one tiny module per pack.
// Run: bun scripts/build-icons.ts (wired as predev/prebuild). Fails loudly when a mapped icon is missing.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { getIconData, iconToSVG } from '@iconify/utils'
import { ICON_ROWS, PACKS, SETS } from '../src/lib/icons/map'

const out = new URL('../src/lib/icons/generated/', import.meta.url)
mkdirSync(out, { recursive: true })
const missing: string[] = []

for (const pack of PACKS) {
  const { prefix, suffix, stroke, col } = SETS[pack]
  const set = JSON.parse(readFileSync(require.resolve(`@iconify-json/${prefix}/icons.json`), 'utf8'))
  const icons: Record<string, [string, string]> = {}
  for (const row of ICON_ROWS) {
    const id = row[col] + suffix
    const data = getIconData(set, id)
    if (!data) { missing.push(`${pack}: ${row[0]} → ${prefix}:${id}`); continue }
    const svg = iconToSVG(data)
    // Stroke sets: let the <svg> element control fill & stroke-width (for tint and :stroke-width).
    const body = stroke ? svg.body.replace(/ (fill="none"|stroke-width="[\d.]+")/g, '') : svg.body
    icons[row[0]] = [svg.attributes.viewBox, body]
  }
  const src = `// Generated by scripts/build-icons.ts — do not edit.\nimport type { PackData } from '..'\n\nconst pack: PackData = ${JSON.stringify({ stroke, icons })}\nexport default pack\n`
  writeFileSync(new URL(`${pack}.ts`, out), src)
}

if (missing.length) {
  console.error(`build-icons: ${missing.length} mapped icon(s) not found:\n  ` + missing.join('\n  '))
  process.exit(1)
}
console.log(`build-icons: ${PACKS.length} packs × ${ICON_ROWS.length} icons`)
